#!/usr/bin/env python3
"""Generates the codecs of the jsoniter oracle (upstream-oracle-tests, package hearth.kindlings.oracle.jsoniter): one
Kindlings codec with the config known at compile time (JoOptimized, Scala 2.13 and Scala 3 versions), one with the same
config only known at runtime (JoRuntime), one from jsoniter-scala's JsonCodecMaker (JoUpstream), and the triples
(JoCases), for every (config, fixture) pair of the table below. Each case also needs a test in JsoniterOracleSpec (with
the samples JoSamples.<fixture>).

Run from the repository root, then format with scalafmt:

    python3 scripts/gen-jsoniter-oracle-codecs.py
"""

import os

root = "upstream-oracle-tests"
GENERATED = "// Generated by scripts/gen-jsoniter-oracle-codecs.py - edit the table there."
D = "JsoniterConfig.jsoniterScalaDefaults"
U = "CodecMakerConfig"
def mk(cfg=None, maker="make"):
    return (lambda T: f"JsonCodecMaker.{maker}[{T}]") if cfg is None else (lambda T: f"JsonCodecMaker.make[{T}]({cfg})")
REC = mk(f"{U}.withAllowRecursiveTypes(true)")
# group: (name, kindlings config, upstream maker, [(case, Type)])
groups = [
 ("upstreamDefaults", D, mk(), [
   ("person","JOPerson"),("defaults","JODefaults"),("emptyable","JOEmptyable"),("nestedOption","JONestedOption"),
   ("primitives","JOPrimitives"),("boxed","JOBoxed"),("big","JOBig"),("wrapped","JOWrapped"),("maps","JOMaps"),
   ("collections","JOCollections"),("nonEmpty","JONonEmpty"),("tuples","JOTuples"),("time","JOTime"),("either","JOEither"),("shape","JOShape"),
   ("circle","JOCircle"),("drawing","JODrawing"),("shapeHolder","JOShapeHolder"),("colour","JOColour"),("enums","JOEnums"),("annotated","JOAnnotated"),
   ("camel","JOCamel"),("user","JOUser"),("scalaTransient","JOScalaTransient"),("stringy","JOStringy"),
   ("listInt","List[Int]"),("setInt","Set[Int]"),("mapIntString","Map[Int, String]"),("optionInt","Option[Int]"),
   ("tupleTop","(Int, Boolean)"),("literal","JOLiteral")]),
 ("upstreamDefaultsRecursive", D, REC, [("tree","JOTree"),("expr","JOExpr")]),
 ("kindlingsDefaults", "JsoniterConfig.default", mk(), [
   ("person","JOPerson"),("defaults","JODefaults"),("emptyable","JOEmptyable"),("nestedOption","JONestedOption"),
   ("shape","JOShape"),("drawing","JODrawing"),("colour","JOColour"),("setInt","Set[Int]"),("mapIntString","Map[Int, String]")]),
 ("snakeCase", f"{D}.withSnakeCaseFieldNames", mk(f"{U}.withFieldNameMapper(JsonCodecMaker.enforce_snake_case)"), [("camel","JOCamel")]),
 ("snakeCase2", f"{D}.withFieldNameMapper(JsoniterConfig.enforce_snake_case2)", mk(f"{U}.withFieldNameMapper(JsonCodecMaker.enforce_snake_case2)"), [("camel","JOCamel")]),
 ("kebabCase", f"{D}.withKebabCaseFieldNames", mk(f"{U}.withFieldNameMapper(JsonCodecMaker.`enforce-kebab-case`)"), [("camel","JOCamel")]),
 ("pascalCase", f"{D}.withPascalCaseFieldNames", mk(f"{U}.withFieldNameMapper(JsonCodecMaker.EnforcePascalCase)"), [("camel","JOCamel")]),
 ("camelCase", f"{D}.withFieldNameMapper(JsoniterConfig.enforceCamelCase)", mk(f"{U}.withFieldNameMapper(JsonCodecMaker.enforceCamelCase)"), [("camel","JOCamel")]),
 ("partialFieldMapper", f'{D}.withFieldNameMapper {{ case "firstName" => "given" }}', mk(f'{U}.withFieldNameMapper {{ case "firstName" => "given" }}'), [("camel","JOCamel")]),
 ("snakeCaseLeaves", f"{D}.withSnakeCaseAdtLeafClassNames", mk(f"{U}.withAdtLeafClassNameMapper(x => JsonCodecMaker.enforce_snake_case(JsonCodecMaker.simpleClassName(x)))"), [("shape","JOShape"),("colour","JOColour")]),
 ("discriminatorKind", f'{D}.withDiscriminator("kind")', mk(f'{U}.withDiscriminatorFieldName(Some("kind"))'), [("shape","JOShape"),("drawing","JODrawing")]),
 ("noDiscriminator", f"{D}.withDiscriminatorFieldName(None)", mk(f"{U}.withDiscriminatorFieldName(None)"), [("shape","JOShape"),("drawing","JODrawing"),("shapeHolder","JOShapeHolder"),("colour","JOColour"),("either","JOEither")]),
 ("discriminatorAnywhere", f"{D}.withRequireDiscriminatorFirst(false)", mk(f"{U}.withRequireDiscriminatorFirst(false)"), [("shape","JOShape")]),
 ("alwaysEmitDiscriminator", f"{D}.withAlwaysEmitDiscriminator", mk(f"{U}.withAlwaysEmitDiscriminator(true)"), [("shape","JOShape"),("circle","JOCircle")]),
 ("circeLike", f"{D}.withDiscriminatorFieldName(None).withCirceLikeObjectEncoding", mk(f"{U}.withDiscriminatorFieldName(None).withCirceLikeObjectEncoding(true)"), [("shape","JOShape"),("shapeHolder","JOShapeHolder"),("colour","JOColour")]),
 ("strict", f"{D}.withSkipUnexpectedFields(false)", mk(f"{U}.withSkipUnexpectedFields(false)"), [("person","JOPerson"),("shape","JOShape")]),
 ("noTransientDefault", f"{D}.copy(transientDefault = false)", mk(f"{U}.withTransientDefault(false)"), [("defaults","JODefaults")]),
 ("noTransientEmpty", f"{D}.copy(transientEmpty = false)", mk(f"{U}.withTransientEmpty(false)"), [("emptyable","JOEmptyable"),("defaults","JODefaults")]),
 ("noTransientNone", f"{D}.copy(transientNone = false)", mk(f"{U}.withTransientNone(false)"), [("emptyable","JOEmptyable"),("nestedOption","JONestedOption")]),
 ("requireCollections", f"{D}.copy(transientEmpty = false).withRequireCollectionFields", mk(f"{U}.withTransientEmpty(false).withRequireCollectionFields(true)"), [("emptyable","JOEmptyable"),("defaults","JODefaults")]),
 ("requireDefaults", f"{D}.copy(transientDefault = false).withRequireDefaultFields", mk(f"{U}.withTransientDefault(false).withRequireDefaultFields(true)"), [("defaults","JODefaults")]),
 ("noDuplicationCheck", f"{D}.copy(checkFieldDuplication = false)", mk(f"{U}.withCheckFieldDuplication(false)"), [("person","JOPerson"),("defaults","JODefaults")]),
 ("stringified", f"{D}.withStringified", mk(f"{U}.withIsStringified(true)"), [("stringy","JOStringy"),("listInt","List[Int]"),("optionInt","Option[Int]"),("tupleTop","(Int, Boolean)"),("mapIntString","Map[Int, String]"),("wrapped","JOWrapped")]),
 ("mapAsArray", f"{D}.withMapAsArray", mk(f"{U}.withMapAsArray(true)"), [("maps","JOMaps"),("mapIntString","Map[Int, String]")]),
 ("bigDecimalPrecision", f"{D}.withBigDecimalPrecision(5)", mk(f"{U}.withBigDecimalPrecision(5)"), [("big","JOBig")]),
 ("bigDecimalScaleLimit", f"{D}.withBigDecimalScaleLimit(2)", mk(f"{U}.withBigDecimalScaleLimit(2)"), [("big","JOBig")]),
 ("bigDecimalDigitsLimit", f"{D}.withBigDecimalDigitsLimit(3)", mk(f"{U}.withBigDecimalDigitsLimit(3)"), [("big","JOBig")]),
 ("bigIntDigitsLimit", f"{D}.withBigIntDigitsLimit(3)", mk(f"{U}.withBigIntDigitsLimit(3)"), [("big","JOBig")]),
 ("insertLimits", f"{D}.withMapMaxInsertNumber(2).withSetMaxInsertNumber(2)", mk(f"{U}.withMapMaxInsertNumber(2).withSetMaxInsertNumber(2)"), [("emptyable","JOEmptyable"),("maps","JOMaps")]),
 ("bitSetValueLimit", f"{D}.withBitSetValueLimit(10)", mk(f"{U}.withBitSetValueLimit(10)"), [("collections","JOCollections")]),
 ("scalaEnumValueId", f"{D}.withUseScalaEnumValueId", mk(f"{U}.withUseScalaEnumValueId(true)"), [("enums","JOEnums")]),
 ("javaEnumValueNameMapper", f"{D}.withJavaEnumValueNameMapper(JsoniterConfig.enforce_snake_case)", mk(f"{U}.withJavaEnumValueNameMapper(JsonCodecMaker.enforce_snake_case)"), [("enums","JOEnums")]),
 ("skipNestedOptionValues", f"{D}.withSkipNestedOptionValues", mk(f"{U}.withSkipNestedOptionValues(true)"), [("nestedOption","JONestedOption")]),
 ("inlineOneValueClasses", f"{D}.withInlineOneValueClasses", mk(f"{U}.withInlineOneValueClasses(true)"), [("user","JOUser"),("nameMap","JONameMap")]),
 ("scalaTransientSupport", f"{D}.withScalaTransientSupport", mk(f"{U}.withScalaTransientSupport(true)"), [("scalaTransient","JOScalaTransient")]),
 ("decodingOnly", f"{D}.withDecodingOnly", mk(f"{U}.withDecodingOnly(true)"), [("person","JOPerson")]),
 ("encodingOnly", f"{D}.withEncodingOnly", mk(f"{U}.withEncodingOnly(true)"), [("person","JOPerson")]),
 ("makeWithoutDiscriminator", "JsoniterConfig.makeWithoutDiscriminator", mk(None,"makeWithoutDiscriminator"), [("shape","JOShape")]),
 ("makeWithRequiredCollectionFields", "JsoniterConfig.makeWithRequiredCollectionFields", mk(None,"makeWithRequiredCollectionFields"), [("emptyable","JOEmptyable")]),
 ("makeWithRequiredDefaultFields", "JsoniterConfig.makeWithRequiredDefaultFields", mk(None,"makeWithRequiredDefaultFields"), [("defaults","JODefaults")]),
 ("makeWithSkipNestedOptionValues", "JsoniterConfig.makeWithSkipNestedOptionValues", mk(None,"makeWithSkipNestedOptionValues"), [("nestedOption","JONestedOption")]),
 ("makeCirceLike", "JsoniterConfig.makeCirceLike", mk(None,"makeCirceLike"), [("shape","JOShape"),("colour","JOColour"),("emptyable","JOEmptyable")]),
 ("makeCirceLikeSnakeCased", "JsoniterConfig.makeCirceLikeSnakeCased", mk(None,"makeCirceLikeSnakeCased"), [("camel","JOCamel"),("shape","JOShape"),("enums","JOEnums")]),
 ("makeOpenapiLike", "JsoniterConfig.makeOpenapiLike", mk(None,"makeOpenapiLike"), [("shape","JOShape"),("defaults","JODefaults"),("emptyable","JOEmptyable")]),
]
def ident(g, c): return g + c[0].upper() + c[1:]
for ver in ("2", "3"):
    using = "using " if ver == "3" else ""
    other = "3" if ver == "2" else "2.13"
    out = [GENERATED, "package hearth.kindlings.oracle.jsoniter", "",
           "import com.github.plokhotnyuk.jsoniter_scala.core.JsonValueCodec",
           "import hearth.kindlings.jsoniterderivation.{JsoniterConfig, KindlingsJsonValueCodec}", "",
           "/** Kindlings codecs derived with configs known at compile time (the optimized codegen), one per oracle case of",
           f"  * `JsoniterOracleSpec`. Kept in sync with the Scala {other} version of this file and with `JoRuntime`/`JoUpstream`:",
           "  * the only difference between the versions is the syntax of passing the config explicitly.", "  */",
           "object JoOptimized {"]
    for g, k, u, cases in groups:
        out.append(f"  // {g}")
        for c, T in cases:
            out.append(f"  lazy val {ident(g,c)}: JsonValueCodec[{T}] = KindlingsJsonValueCodec.derived[{T}]({using}{k})")
    out.append("}")
    p = f"{root}/src/test/scala-{ver}/hearth/kindlings/oracle/jsoniter/JoOptimized.scala"
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write("\n".join(out) + "\n")
# runtime
out = [GENERATED, "package hearth.kindlings.oracle.jsoniter", "",
       "import com.github.plokhotnyuk.jsoniter_scala.core.JsonValueCodec",
       "import hearth.kindlings.jsoniterderivation.{JsoniterConfig, KindlingsJsonValueCodec}", "",
       "/** The configs of `JoOptimized`, only known at runtime (`@volatile var`s), so that the codecs of `JoRuntime` use the",
       "  * generic codegen.", "  */",
       "object JoRuntimeConfigs {"]
for g, k, u, cases in groups:
    out.append(f"  @volatile var {g}: JsoniterConfig = {k}")
out += ["}", "", "/** Kindlings codecs derived with the configs of `JoRuntimeConfigs` (the generic codegen). */", "object JoRuntime {"]
for g, k, u, cases in groups:
    out.append(f"  object {g} {{")
    out.append(f"    implicit def config: JsoniterConfig = JoRuntimeConfigs.{g}")
    for c, T in cases:
        out.append(f"    lazy val {c}: JsonValueCodec[{T}] = KindlingsJsonValueCodec.derived[{T}]")
    out.append("  }")
out.append("}")
open(f"{root}/src/test/scala/hearth/kindlings/oracle/jsoniter/JoRuntime.scala","w").write("\n".join(out)+"\n")
out = [GENERATED, "package hearth.kindlings.oracle.jsoniter", "",
       "import com.github.plokhotnyuk.jsoniter_scala.core.JsonValueCodec",
       "import com.github.plokhotnyuk.jsoniter_scala.macros.{CodecMakerConfig, JsonCodecMaker}", "",
       "/** jsoniter-scala's codecs (`JsonCodecMaker.make` with the `CodecMakerConfig` equivalent to each Kindlings config, or",
       "  * the `makeXxx` entry point equivalent to each preset). Recursive types need `allowRecursiveTypes` upstream.", "  */",
       "// jsoniter-scala's Scala 2 macro leaves unused local vars in some ADT decoders.", "@scala.annotation.nowarn(\"msg=is never used\")", "object JoUpstream {"]
for g, k, u, cases in groups:
    out.append(f"  object {g} {{")
    for c, T in cases:
        out.append(f"    lazy val {c}: JsonValueCodec[{T}] = {u(T)}")
    out.append("  }")
out.append("}")
open(f"{root}/src/test/scala/hearth/kindlings/oracle/jsoniter/JoUpstream.scala","w").write("\n".join(out)+"\n")
out = [GENERATED, "package hearth.kindlings.oracle.jsoniter", "",
       "/** The three codecs of every oracle case: `JoCases.<config>.<fixture>`. */",
       "object JoCases {"]
for g, k, u, cases in groups:
    out.append(f"  object {g} {{")
    for c, T in cases:
        out.append(f"    def {c}: JoCodecs[{T}] = JoCodecs(JoOptimized.{ident(g,c)}, JoRuntime.{g}.{c}, JoUpstream.{g}.{c})")
    out.append("  }")
out.append("}")
open(f"{root}/src/test/scala/hearth/kindlings/oracle/jsoniter/JoCases.scala","w").write("\n".join(out)+"\n")
