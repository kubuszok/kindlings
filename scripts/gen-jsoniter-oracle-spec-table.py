def cfg(k, u):
    """A Kindlings config built on upstream's defaults and the equivalent CodecMakerConfig."""
    return (f"{D}{k}", mk(f"{U}{u}"))

def group(name, kcfg_u, cases):
    return (name, kcfg_u[0], kcfg_u[1], cases)

def preset(name, cases, maker=None):
    return (name, f"JsoniterConfig.{maker or name}", mk(None, maker or name), cases)

