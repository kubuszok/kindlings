package hearth.kindlings.catsderivation.internal.compiletime

import hearth.MacroCommons
import hearth.fp.effect.*
import hearth.fp.instances.*
import hearth.fp.syntax.*
import hearth.std.*

/** Apply / Applicative / Pure / Reducible / NonEmptyTraverse / NonEmptyAlternative / Alternative for case classes with
  * fields wrapping the type parameter (`tail: List[A]`, `children: List[Tree[A]]`, `opt: Option[Vector[A]]`), like
  * kittens: every field gets an instance - `Id`'s for a field of type `A`, a `Const`-like one for a constant field, the
  * wrapping type's (composed for `G[H[A]]`, the instance being defined for a field mentioning the case class itself)
  * otherwise - and `HktWrappedRuntime` combines them field by field. Shapes kittens rejects are rejected with the
  * reason (a missing instance for the wrapping type, no non-empty field for Reducible / NonEmptyTraverse, ...).
  *
  * Case classes whose fields are all `A` or constant keep the specialised code generated by each macro.
  */
trait WrappedFieldsSupport extends CatsDerivationTimeout with CatsDerivationErrorSupport {
  this: MacroCommons & StdExtensions =>

  /** Runs [[deriveWrappedFieldsInstance]] as a macro expansion, rendering errors like the other derivations. */
  protected def runWrappedFieldsDerivation[F[_], Out: Type](tc: WrappedTC, macroName: String)(implicit
      FCtor: Type.Ctor1[F]
  ): Expr[Out] = {
    implicit val LogDerivationType: Type[hearth.kindlings.catsderivation.LogDerivation] =
      Type.of[hearth.kindlings.catsderivation.LogDerivation]
    val shouldLog = Expr.summonImplicit[hearth.kindlings.catsderivation.LogDerivation].isDefined || (for {
      data <- Environment.typedSettings.toOption
      cd <- data.get("catsDerivation")
      log <- cd.get("logDerivation").flatMap(_.asBoolean)
    } yield log).getOrElse(false)
    Log
      .namedScope(s"Deriving ${tc.name} at: ${Environment.currentPosition.prettyPrint}") {
        deriveWrappedFieldsInstance[F, Out](tc)
      }
      .flatTap(result => Log.info(s"Derived final result: ${result.prettyPrint}"))
      .runToExprOrFail(
        macroName,
        infoRendering = if (shouldLog) RenderFrom(Log.Level.Info) else DontRender,
        errorRendering = if (shouldLog) RenderFrom(Log.Level.Info) else DontRender,
        timeout = derivationTimeout
      ) { (errorLogs, errors) =>
        val errorsRendered =
          hearth.kindlings.derivation.compiletime.DerivationErrorRendering.renderErrors(errors.toVector)
        val hint =
          "Enable debug logging with: import hearth.kindlings.catsderivation.debug.logDerivationForCatsDerivation"
        if (errorLogs.nonEmpty) s"Macro derivation failed:\n$errorsRendered\nlogs:\n$errorLogs\n$hint"
        else s"Macro derivation failed:\n$errorsRendered\n$hint"
      }
  }

  sealed abstract class WrappedTC(val name: String)
  object WrappedTC {
    case object Apply extends WrappedTC("Apply")
    case object Applicative extends WrappedTC("Applicative")
    case object Pure extends WrappedTC("Pure")
    case object Reducible extends WrappedTC("Reducible")
    case object NonEmptyTraverse extends WrappedTC("NonEmptyTraverse")
    case object NonEmptyAlternative extends WrappedTC("NonEmptyAlternative")
    case object Alternative extends WrappedTC("Alternative")
  }

  private type WrappedAnyK[X] = Any

  private lazy val WrappedIntType: Type[Int] = Type.of[Int]
  private lazy val WrappedStringType: Type[String] = Type.of[String]
  private lazy val WrappedAnyType: Type[Any] = Type.of[Any]
  private lazy val WrappedApplyCtor: Type.CtorK1[cats.Apply] = Type.CtorK1.of[cats.Apply]
  private lazy val WrappedApplicativeCtor: Type.CtorK1[cats.Applicative] = Type.CtorK1.of[cats.Applicative]
  private lazy val WrappedPureCtor: Type.CtorK1[alleycats.Pure] = Type.CtorK1.of[alleycats.Pure]
  private lazy val WrappedFoldableCtor: Type.CtorK1[cats.Foldable] = Type.CtorK1.of[cats.Foldable]
  private lazy val WrappedReducibleCtor: Type.CtorK1[cats.Reducible] = Type.CtorK1.of[cats.Reducible]
  private lazy val WrappedTraverseCtor: Type.CtorK1[cats.Traverse] = Type.CtorK1.of[cats.Traverse]
  private lazy val WrappedNonEmptyTraverseCtor: Type.CtorK1[cats.NonEmptyTraverse] =
    Type.CtorK1.of[cats.NonEmptyTraverse]
  private lazy val WrappedNonEmptyAlternativeCtor: Type.CtorK1[cats.NonEmptyAlternative] =
    Type.CtorK1.of[cats.NonEmptyAlternative]
  private lazy val WrappedAlternativeCtor: Type.CtorK1[cats.Alternative] = Type.CtorK1.of[cats.Alternative]
  private lazy val WrappedSemigroupCtor: Type.Ctor1[cats.kernel.Semigroup] = Type.Ctor1.of[cats.kernel.Semigroup]
  private lazy val WrappedMonoidCtor: Type.Ctor1[cats.kernel.Monoid] = Type.Ctor1.of[cats.kernel.Monoid]
  private lazy val WrappedEmptyCtor: Type.Ctor1[alleycats.Empty] = Type.Ctor1.of[alleycats.Empty]

  /** Whether `F` is a case class with at least one field wrapping its type parameter. */
  protected def hasWrappedFields[F[_]](implicit FCtor: Type.Ctor1[F]): Boolean =
    (
      CaseClass.parse(using FCtor.apply[Int](using WrappedIntType)).toOption,
      CaseClass.parse(using FCtor.apply[String](using WrappedStringType)).toOption
    ) match {
      case (Some(ccInt), Some(ccString)) =>
        ccInt.primaryConstructor.totalParameters.flatten.toList
          .zip(ccString.primaryConstructor.totalParameters.flatten.toList)
          .exists { case ((_, pInt), (_, pString)) =>
            val tInt = pInt.tpe.Underlying
            val tString = pString.tpe.Underlying
            !(tInt =:= WrappedIntType && tString =:= WrappedStringType) && !(tInt =:= tString)
          }
      case _ => false
    }

  /** A field's instance (erased) and whether it guarantees an element (for Reducible / NonEmptyTraverse). */
  final private case class FieldInstance(instance: Expr[Any], nonEmpty: Boolean)

  @scala.annotation.nowarn("msg=is never used|unused implicit parameter|unused explicit parameter")
  protected def deriveWrappedFieldsInstance[F[_], Out: Type](tc: WrappedTC)(implicit
      FCtor: Type.Ctor1[F]
  ): MIO[Expr[Out]] = {
    implicit val IntType: Type[Int] = WrappedIntType
    implicit val StringType: Type[String] = WrappedStringType
    implicit val AnyType: Type[Any] = WrappedAnyType
    implicit val FAnyType: Type[F[Any]] = FCtor.apply[Any]
    val parentCtor = FCtor.asUntyped

    for {
      _ <- Environment.loadStandardExtensions().toMIO(allowFailures = false)
      ccInt <- parseCaseClassMIO[F[Int]]("F[Int]")(using FCtor.apply[Int])
      ccString <- parseCaseClassMIO[F[String]]("F[String]")(using FCtor.apply[String])
      ccAny <- parseCaseClassMIO[F[Any]]("F[Any]")
      result <- {
        val fieldsInt = ccInt.primaryConstructor.totalParameters.flatten.toList
        val fieldsString = ccString.primaryConstructor.totalParameters.flatten.toList
        val fieldsAny = ccAny.primaryConstructor.totalParameters.flatten.toList

        // Field instances, built inside the `self => ...` lambda (the instance being defined).
        def fieldInstances(self: Expr[Any]): Either[List[CatsDerivationError], List[FieldInstance]] = {
          val results = fieldsInt.zip(fieldsString).map { case ((name, pInt), (_, pString)) =>
            val tInt = pInt.tpe.Underlying.asInstanceOf[Type[Any]]
            val tString = pString.tpe.Underlying
            val result: Either[String, FieldInstance] =
              if (tInt =:= IntType && tString =:= StringType) directInstance(tc)
              else if (tInt =:= tString) constantInstance(tc, tInt)
              else wrappedInstance(tc, tInt, self, parentCtor)
            result.left
              .map(reason => CatsDerivationError.UnsupportedFieldShape(tc.name, name, reason): CatsDerivationError)
          }
          val errors = results.collect { case Left(e) => e }
          if (errors.nonEmpty) Left(errors) else Right(results.collect { case Right(i) => i })
        }

        // Validate once (with a placeholder for `self`) so that errors are reported before code generation.
        fieldInstances(Expr.quote(null: Any)) match {
          case Left(head :: tail) =>
            Log.error((head :: tail).map(_.message).mkString("\n")) >> MIO.fail(head, tail*)
          case Left(Nil) => MIO.fail(CatsDerivationError.CannotParseCaseClass(Type[F[Any]].prettyPrint, "no fields"))
          case Right(instances) =>
            val needsNonEmpty = tc == WrappedTC.Reducible || tc == WrappedTC.NonEmptyTraverse
            if (needsNonEmpty && !instances.exists(_.nonEmpty))
              failDerivation(
                CatsDerivationError.UnsupportedFieldShape(
                  tc.name,
                  fieldsInt.map(_._1).mkString(", "),
                  s"no field guarantees an element: like kittens, at least one field must be of the type parameter or " +
                    s"wrap it in a ${if (tc == WrappedTC.Reducible) "Reducible" else "NonEmptyTraverse"} type"
                )
              )
            else
              MIO.scoped { runSafe =>
                // Splice bodies are plain functions (Scala 2's cross-quotes keep splices simple).
                val fieldsBody: Expr[Any] => Expr[Array[Any]] = { fa =>
                  val value: Expr[F[Any]] = Expr.quote(Expr.splice(fa).asInstanceOf[F[Any]])
                  arrayOf(ccAny.caseFieldValuesAt(value).toList.map { case (_, fieldValue) =>
                    import fieldValue.Underlying as Field
                    fieldValue.value.asInstanceOf[Expr[Field]].upcast[Any]
                  })
                }
                val constructBody: Expr[Array[Any]] => Expr[Any] = { values =>
                  val args: Map[String, Expr_??] = fieldsAny.zipWithIndex.map { case ((name, param), index) =>
                    name -> castTo(Expr.quote(Expr.splice(values)(Expr.splice(Expr(index)))), param.tpe)
                  }.toMap
                  runSafe(
                    constructInstanceFree(ccAny.primaryConstructor, "Constructor", Type[F[Any]].prettyPrint)(args)
                  ).value
                    .asInstanceOf[Expr[Any]]
                }
                val instancesBody: Expr[Any] => Expr[Array[Any]] = { self =>
                  arrayOf(fieldInstances(self).toOption.get.map(_.instance))
                }
                val fieldsFn: Expr[Any => Array[Any]] = Expr.quote((fa: Any) => Expr.splice(fieldsBody(Expr.quote(fa))))
                val constructFn: Expr[Array[Any] => Any] =
                  Expr.quote((values: Array[Any]) => Expr.splice(constructBody(Expr.quote(values))))
                val instancesFn: Expr[Any => Array[Any]] =
                  Expr.quote((self: Any) => Expr.splice(instancesBody(Expr.quote(self))))
                buildInstance[F, Out](tc, fieldsFn, constructFn, instancesFn)
              }
        }
      }
    } yield result
  }

  private def castTo(value: Expr[Any], targetType: ??): Expr_?? = {
    import targetType.Underlying as T
    Expr.quote(Expr.splice(value).asInstanceOf[T]).as_??
  }

  private def arrayOf(values: List[Expr[Any]]): Expr[Array[Any]] = {
    val list = values.foldRight(Expr.quote(List.empty[Any])) { (value, acc) =>
      Expr.quote(Expr.splice(value) :: Expr.splice(acc))
    }
    Expr.quote(Expr.splice(list).toArray[Any])
  }

  @scala.annotation.nowarn("msg=is never used|unused implicit parameter")
  private def buildInstance[F[_], Out: Type](
      tc: WrappedTC,
      fieldsFn: Expr[Any => Array[Any]],
      constructFn: Expr[Array[Any] => Any],
      instancesFn: Expr[Any => Array[Any]]
  )(implicit FCtor: Type.Ctor1[F]): Expr[Out] =
    tc match {
      case WrappedTC.Apply =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .applyInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.Applicative =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .applicativeInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.Pure =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .pureInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.Reducible =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .reducibleInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.NonEmptyTraverse =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .nonEmptyTraverseInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.NonEmptyAlternative =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .nonEmptyAlternativeInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
      case WrappedTC.Alternative =>
        Expr.quote {
          hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
            .alternativeInstance[F](Expr.splice(fieldsFn), Expr.splice(constructFn), Expr.splice(instancesFn))
            .asInstanceOf[Out]
        }
    }

  private def directInstance(tc: WrappedTC): Either[String, FieldInstance] = {
    implicit val AnyType: Type[Any] = WrappedAnyType
    tc match {
      case WrappedTC.Pure =>
        Right(
          FieldInstance(
            Expr.quote(hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.idPure),
            nonEmpty = true
          )
        )
      case WrappedTC.NonEmptyAlternative | WrappedTC.Alternative =>
        Left(s"a field of the type parameter itself has no ${tc.name} (like kittens: every field must wrap it)")
      case _ =>
        Right(
          FieldInstance(
            Expr.quote(hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.idApplicative),
            nonEmpty = true
          )
        )
    }
  }

  private def constantInstance(tc: WrappedTC, fieldType: Type[Any]): Either[String, FieldInstance] = {
    implicit val AnyType: Type[Any] = WrappedAnyType
    def summonKernel(ctor: Type.Ctor1[cats.kernel.Semigroup], label: String): Either[String, Expr[Any]] = {
      val kernelType: Type[Any] = ctor.apply[Any](using fieldType).asInstanceOf[Type[Any]]
      Expr
        .summonImplicit[Any](using kernelType)
        .toOption
        .map(_.asInstanceOf[Expr[Any]])
        .toRight(
          s"the constant field needs a $label[${fieldType.prettyPrint}]"
        )
    }
    tc match {
      case WrappedTC.Apply =>
        summonKernel(WrappedSemigroupCtor, "Semigroup").map(sg =>
          FieldInstance(
            Expr.quote(hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.constApply(Expr.splice(sg))),
            nonEmpty = false
          )
        )
      case WrappedTC.Applicative =>
        summonKernel(WrappedMonoidCtor.asInstanceOf[Type.Ctor1[cats.kernel.Semigroup]], "Monoid").map(m =>
          FieldInstance(
            Expr.quote(
              hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.constApplicative(Expr.splice(m))
            ),
            nonEmpty = false
          )
        )
      case WrappedTC.Pure =>
        summonKernel(WrappedEmptyCtor.asInstanceOf[Type.Ctor1[cats.kernel.Semigroup]], "Empty").map(e =>
          FieldInstance(
            Expr.quote(hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.constPure(Expr.splice(e))),
            nonEmpty = false
          )
        )
      case WrappedTC.Reducible | WrappedTC.NonEmptyTraverse =>
        Right(
          FieldInstance(
            Expr.quote(hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime.constTraverse),
            nonEmpty = false
          )
        )
      case WrappedTC.NonEmptyAlternative | WrappedTC.Alternative =>
        summonKernel(WrappedMonoidCtor.asInstanceOf[Type.Ctor1[cats.kernel.Semigroup]], "Monoid").map(m =>
          FieldInstance(
            Expr.quote(
              hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                .constNonEmptyAlternative(Expr.splice(m))
            ),
            nonEmpty = false
          )
        )
    }
  }

  /** The instance for a field `G[X]` (probed with `Int` for the type parameter). */
  private def wrappedInstance(
      tc: WrappedTC,
      fieldType: Type[Any],
      self: Expr[Any],
      parentCtor: UntypedType
  ): Either[String, FieldInstance] = {
    implicit val AnyType: Type[Any] = WrappedAnyType
    Type.decompose1(using fieldType) match {
      case None =>
        Left(s"${fieldType.prettyPrint} is not a type constructor applied to the type parameter")
      case Some((gCtor, arg)) =>
        val inner = arg.Underlying.asInstanceOf[Type[Any]]
        val isSelf = gCtor.asUntyped.sameTypeConstructorAs(parentCtor)

        // The wrapping type's instance (and, for Reducible / NonEmptyTraverse, whether it guarantees an element).
        def summonFor(kind: String): Option[Expr[Any]] = kind match {
          case "Apply" =>
            implicit val T: Type[cats.Apply[WrappedAnyK]] =
              WrappedApplyCtor.apply(using gCtor).asInstanceOf[Type[cats.Apply[WrappedAnyK]]]
            Expr.summonImplicit[cats.Apply[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "Applicative" =>
            implicit val T: Type[cats.Applicative[WrappedAnyK]] =
              WrappedApplicativeCtor.apply(using gCtor).asInstanceOf[Type[cats.Applicative[WrappedAnyK]]]
            Expr.summonImplicit[cats.Applicative[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "Pure" =>
            implicit val T: Type[alleycats.Pure[WrappedAnyK]] =
              WrappedPureCtor.apply(using gCtor).asInstanceOf[Type[alleycats.Pure[WrappedAnyK]]]
            Expr.summonImplicit[alleycats.Pure[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "Foldable" =>
            implicit val T: Type[cats.Foldable[WrappedAnyK]] =
              WrappedFoldableCtor.apply(using gCtor).asInstanceOf[Type[cats.Foldable[WrappedAnyK]]]
            Expr.summonImplicit[cats.Foldable[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "Reducible" =>
            implicit val T: Type[cats.Reducible[WrappedAnyK]] =
              WrappedReducibleCtor.apply(using gCtor).asInstanceOf[Type[cats.Reducible[WrappedAnyK]]]
            Expr.summonImplicit[cats.Reducible[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "Traverse" =>
            implicit val T: Type[cats.Traverse[WrappedAnyK]] =
              WrappedTraverseCtor.apply(using gCtor).asInstanceOf[Type[cats.Traverse[WrappedAnyK]]]
            Expr.summonImplicit[cats.Traverse[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "NonEmptyTraverse" =>
            implicit val T: Type[cats.NonEmptyTraverse[WrappedAnyK]] =
              WrappedNonEmptyTraverseCtor.apply(using gCtor).asInstanceOf[Type[cats.NonEmptyTraverse[WrappedAnyK]]]
            Expr.summonImplicit[cats.NonEmptyTraverse[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case "NonEmptyAlternative" =>
            implicit val T: Type[cats.NonEmptyAlternative[WrappedAnyK]] =
              WrappedNonEmptyAlternativeCtor
                .apply(using gCtor)
                .asInstanceOf[Type[cats.NonEmptyAlternative[WrappedAnyK]]]
            Expr.summonImplicit[cats.NonEmptyAlternative[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
          case _ =>
            implicit val T: Type[cats.Alternative[WrappedAnyK]] =
              WrappedAlternativeCtor.apply(using gCtor).asInstanceOf[Type[cats.Alternative[WrappedAnyK]]]
            Expr.summonImplicit[cats.Alternative[WrappedAnyK]].toOption.map(_.asInstanceOf[Expr[Any]])
        }

        val (outerKind, nonEmptyKind) = tc match {
          case WrappedTC.Reducible        => ("Foldable", Some("Reducible"))
          case WrappedTC.NonEmptyTraverse => ("Traverse", Some("NonEmptyTraverse"))
          case other                      => (other.name, None)
        }
        val outerOpt: Option[Expr[Any]] = if (isSelf) Some(self) else summonFor(outerKind)
        val outerNonEmpty: Boolean = isSelf || nonEmptyKind.exists(k => summonFor(k).isDefined)

        outerOpt match {
          case None =>
            Left(s"no $outerKind[${gCtor.asUntyped.prettyPrint}] found for ${fieldType.prettyPrint}")
          case Some(outer) =>
            if (inner =:= WrappedIntType) Right(FieldInstance(outer, outerNonEmpty))
            else {
              // `G[H[A]]`: kittens composes G's instance with H's (an Applicative for H under (NonEmpty)Alternative).
              val innerTc = tc match {
                case WrappedTC.NonEmptyAlternative | WrappedTC.Alternative => WrappedTC.Applicative
                case other                                                 => other
              }
              val innerResult =
                if (inner =:= WrappedIntType) directInstance(innerTc)
                else wrappedInstance(innerTc, inner, self, parentCtor)
              innerResult.map { innerInstance =>
                val i = innerInstance.instance
                val composed: Expr[Any] = tc match {
                  case WrappedTC.Apply =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                        .composeApply(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.Applicative =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                        .composeApplicative(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.Pure =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                        .composePure(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.Reducible =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktNestedRuntime
                        .composeFoldable(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.NonEmptyTraverse =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktNestedRuntime
                        .composeTraverse(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.NonEmptyAlternative =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                        .composeNonEmptyAlternative(Expr.splice(outer), Expr.splice(i))
                    )
                  case WrappedTC.Alternative =>
                    Expr.quote(
                      hearth.kindlings.catsderivation.internal.runtime.HktWrappedRuntime
                        .composeAlternative(Expr.splice(outer), Expr.splice(i))
                    )
                }
                FieldInstance(composed, outerNonEmpty && innerInstance.nonEmpty)
              }
            }
        }
    }
  }
}
